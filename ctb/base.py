def item(**dados):
    base = {
        "inciso": None,
        "multiplicador": 1,
        "medidas": [],
        "responsavel": "condutor",
        "lanca_pontos": True,
        "sanavel_no_local": False,
        "circulacao_insegura": False,
        "comunicar_policia": False,
        "suspensao": None,
        "observacao": "",
        "conduta": [],
        "penalidade_extra": "",
    }
    base.update(dados)
    if "lanca_pontos" not in dados and base["responsavel"] != "condutor":
        base["lanca_pontos"] = False
    if dados.get("orientacao"):
        base["advertencia"] = False
    elif base["natureza"] in ("grave", "gravissima"):
        base["advertencia"] = False
    else:
        base["advertencia"] = True
    return base


